#!/usr/bin/env bash
set -euo pipefail

APP_DIR="${APP_DIR:-/opt/live-trade-angel/app}"
APP_USER="${APP_USER:-ubuntu}"
DB_NAME="${DB_NAME:-live_trade}"
DB_USER="${DB_USER:-live_trade}"
ENV_FILE="${ENV_FILE:-/etc/live-trade-angel.env}"
SERVICE_NAME="live-trade-angel"

if [[ $EUID -ne 0 ]]; then echo "Run with sudo: sudo bash scripts/ec2_install.sh"; exit 1; fi
if [[ ! -f "$APP_DIR/supervisor.py" || ! -f "$APP_DIR/requirements.txt" ]]; then
  echo "Expected application at $APP_DIR. Set APP_DIR if your checkout is elsewhere."; exit 1
fi

export DEBIAN_FRONTEND=noninteractive
apt-get update
apt-get install -y postgresql postgresql-contrib python3 python3-venv python3-dev build-essential libpq-dev git
systemctl enable --now postgresql

DB_PASSWORD="$(python3 -c 'import secrets; print(secrets.token_urlsafe(32))')"
runuser -u postgres -- psql -v ON_ERROR_STOP=1 -v db_user="$DB_USER" -v db_name="$DB_NAME" -v db_password="$DB_PASSWORD" <<'SQL'
SELECT format('CREATE ROLE %I LOGIN PASSWORD %L', :'db_user', :'db_password')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'db_user') \gexec
SELECT format('ALTER ROLE %I WITH LOGIN PASSWORD %L', :'db_user', :'db_password') \gexec
SELECT format('CREATE DATABASE %I OWNER %I', :'db_name', :'db_user')
WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = :'db_name') \gexec
SQL

install -d -o "$APP_USER" -g "$APP_USER" "$APP_DIR/data" "$APP_DIR/logs"
python3 -m venv "$APP_DIR/.venv"
chown -R "$APP_USER:$APP_USER" "$APP_DIR/.venv"
sudo -u "$APP_USER" "$APP_DIR/.venv/bin/pip" install --upgrade pip wheel
sudo -u "$APP_USER" "$APP_DIR/.venv/bin/pip" install -r "$APP_DIR/requirements.txt"

umask 077
cat > "$ENV_FILE" <<EOF
# Generated by ec2_install.sh. Keep this file private (root-readable only).
DATABASE_URL=postgresql://${DB_USER}:${DB_PASSWORD}@127.0.0.1:5432/${DB_NAME}
MARKET_TIMEZONE=Asia/Kolkata
SNAPSHOT_SOURCE=postgres
SNAPSHOT_MAX_AGE_SECONDS=60
OPTION_RETENTION_DAYS=0
TRADING_MODE=paper
TRADING_ENABLED=false
ALLOW_ORDER_SUBMISSION=false
LIVE_SHADOW=true
PAPER_LEDGER_ENABLED=true
DISABLE_SYSTEM_SHUTDOWN=true
EOF
chmod 600 "$ENV_FILE"

install -m 0644 "$APP_DIR/systemd/live-trade-angel.service" "/etc/systemd/system/${SERVICE_NAME}.service"
systemctl daemon-reload
systemctl enable "$SERVICE_NAME"
echo
echo "EC2 base installation complete. Service is ENABLED but NOT STARTED."
echo "Next: restore the Railway PostgreSQL dump, add Angel One/Telegram secrets to $ENV_FILE,"
echo "then validate the database and run: sudo systemctl start $SERVICE_NAME"
